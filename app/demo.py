"""Synthetic demo project for local demos. Run it through the CLI: uv run python -m app.cli seed-demo

Creates, if missing:
- the project (default code DEMO-LEAVE) owned by the demo admin, who also holds the reviewer and
  customer_approver roles on THIS project only, so one login can review, approve and sign off UAT
- the Business Analyst agent service account, as the project's agent
- a demo author (project manager) so there is someone other than the admin to write documents:
  nobody may approve a document they authored
- a synthetic project brief written by the demo author, and Phase 7 moved to in progress, so the Business
  Analyst agent can be asked about the brief straight away
- Phase tasks added to config after the project opened, with earlier agent runs linked to them

All names are synthetic. Nothing here is generated by a model.
"""

from collections.abc import Callable

from app.composition import Services
from app.modules.errors import ConflictError, NotFoundError, ValidationFailedError
from app.modules.artifacts.service import ArtifactCreate
from app.modules.identity.service import SYSTEM_ACTOR, Actor
from app.modules.projects.service import ProjectCreate
from app.modules.workflow.service import TransitionRequest

DEMO_DESCRIPTION = (
    "Synthetic demo project: a leave-request system for a fictional UAE company. "
    "The admin holds owner, reviewer and customer approver roles here for demonstration only."
)

DEMO_BRIEF_TITLE = "Leave management brief"
DEMO_BRIEF = """# Leave management - project brief

**Customer:** Example Trading LLC (synthetic), a trading company with about 220 employees across a head office
in Dubai, a branch in Abu Dhabi and a warehouse in Jebel Ali.

## Background
Leave requests are made by email or on paper forms. HR keeps balances in an Excel workbook. Managers often
approve leave without seeing who else is away, and HR spends about two days each month reconciling balances
before payroll.

## What the customer wants
- Employees request annual, sick, unpaid and compassionate leave online, including from their phones.
- Line managers approve or reject requests and can see their team's calendar before deciding.
- HR can see and correct all requests and balances.
- Balances are calculated according to UAE labour law and visible to employees.
- Warehouse staff work in shifts; some of them do not have company email accounts.
- Monthly leave reports for HR and the finance team, ready before payroll.

## Constraints and context
- The company already uses Microsoft 365, and staff sign in with company accounts.
- Payroll runs on a separate system; the vendor has not confirmed whether it offers an API.
- The first version should be live within three months.
- The internal IT team is two people, and the budget is limited.
- Arabic and English are both used in the company.
"""
DEMO_PHASE = 7


def _ensure_user(services: Services, email: str, create: Callable[[], object]) -> Actor:
    try:
        return services.identity.actor_by_email(email)
    except NotFoundError:
        create()
        return services.identity.actor_by_email(email)


def _ensure_role(services: Services, owner: Actor, project_id: object, email: str, role: str) -> None:
    try:
        services.identity.add_member(owner, project_id, email, role)  # type: ignore[arg-type]
    except ConflictError:
        pass  # already has it


def seed_demo(
    services: Services, *, admin_email: str, author_email: str, code: str, read_password: Callable[[], str]
) -> list[str]:
    """Returns human-readable lines describing what exists afterwards."""
    admin = services.identity.actor_by_email(admin_email)
    if not admin.is_platform_admin:
        raise ValidationFailedError(f"{admin_email} must be a platform administrator to own the demo project")

    project = next((p for p in services.projects.list_projects(admin) if p.code == code), None)
    created = project is None
    if project is None:
        project = services.projects.create_project(
            admin,
            ProjectCreate(code=code, name="Leave Management (demo)", customer_name="Example Trading LLC (synthetic)", description=DEMO_DESCRIPTION),
        )
    for role in ("reviewer", "customer_approver"):
        _ensure_role(services, admin, project.id, admin_email, role)

    agent = services.identity.agent_by_key("business_analyst")
    if agent is None:
        services.identity.create_user(
            SYSTEM_ACTOR,
            email="business_analyst@agents.agentra.local",
            display_name="Business Analyst Agent",
            kind="agent",
            agent_key="business_analyst",
        )
    _ensure_role(services, admin, project.id, "business_analyst@agents.agentra.local", "agent")

    _ensure_user(
        services,
        author_email,
        lambda: services.identity.create_user(
            SYSTEM_ACTOR, email=author_email, display_name="Demo Author (PM)", password=read_password()
        ),
    )
    _ensure_role(services, admin, project.id, author_email, "project_manager")

    author = services.identity.actor_by_email(author_email)
    artifacts = services.artifacts.list_artifacts(admin, project.id)
    if not any(artifact.artifact_type == "project_brief" for artifact in artifacts):
        services.artifacts.create_artifact(
            author, project.id, ArtifactCreate(artifact_type="project_brief", title=DEMO_BRIEF_TITLE, content=DEMO_BRIEF)
        )
    for target in ("ready", "in_progress"):
        phase = next(p for p in services.workflow.list_phase_runs(admin, project.id) if p.phase == DEMO_PHASE)
        if target in phase.available_transitions:
            services.workflow.transition_phase_run(
                admin, phase.id, TransitionRequest(to_state=target, reason="Demo setup", expected_version=phase.version)
            )
    phase_state = services.workflow.phase_state(project.id, DEMO_PHASE)
    added = services.workflow.sync_tasks(admin, project.id)
    linked = services.executions.link_earlier_runs(admin, project.id)

    roles = sorted(services.identity.roles_for(admin, project.id))
    return [
        f"{'Created' if created else 'Found'} demo project {project.code} ({project.id})",
        f"{admin_email} roles on {project.code}: {', '.join(roles)}",
        "Business Analyst Agent is the project's agent",
        f"{author_email} is the project's project manager (writes documents for the admin to review)",
        f"Project brief '{DEMO_BRIEF_TITLE}' is on the project; Phase {DEMO_PHASE} is {(phase_state or '').replace('_', ' ')}",
        *([f"Added tasks defined since the project opened: {', '.join(added)}"] if added else []),
        *([f"Linked {linked} earlier agent run(s) to their tasks"] if linked else []),
    ]
